// not meant to be tested by the `wcc` compiler!!!
long one(void)
{
	return 1;
}

long two(long x)
{
	return 2 * x;
}

long argument_waster(long a, long b, long c, long d, long e, long f, long g,
					 long h, long i, long j, long k, long l)
{
	return a + b + c + d + e + f + g + h + i + j + k + l;
}
